class FenwickTree:
    def __init__(self, a):
        """
        Создаёт дерево Фенвика и заполняет его значениями массива

        a — исходный массив
        self.n — количество элементов
        self.a — копия исходного массива
        self.t — внутренний массив дерева Фенвика
        """

        self.a = a.copy() # копия исходного массива, чтобы метод set() мог узнать старое значение
                          # элемента и вычислить величину изменения.

        self.n = len(a)
        self.t = [0] * (self.n + 1) # на 1 больше, так как индексация начинается с 1 (0 не используется)

        # построение дерева Фенвика
        for i in range(self.n):
            self.add(i + 1, a[i])

    def add(self, k, delta):
        """
        Увеличивает элемент дерева с индексом k на delta

        k — индекс в дереве, начинается с 1
        delta — величина изменения
        """

        # пока индекс находится внутри дерева,
        # обновляем все элементы, содержащие изменяемый элемент
        while k <= self.n:
            self.t[k] += delta
            k += k & -k

    def set(self, i, x):
        """
        Устанавливает исходный элемент с индексом i в значение x

        i — индекс исходного массива, начинается с 0
        x — новое значение элемента
        """

        delta = x - self.a[i]

        # обновляем копию исходного массива
        self.a[i] += delta

        # так как индексация с 1, а изменяется элемент исходного массива, где индексация с 0,
        # то в метод add() передаем i + 1
        self.add(i + 1, delta)

    def prefix_sum(self, r):
        """
        Возвращает сумму исходного массива от 0 до r включительно

        r — индекс последнего элемента исходного массива,
        до которого включительно мы хотим произвести сумму
        """

        r += 1 # так как у нас индексация с 1, а изначально r - индекс исходного массива
        total = 0 # накапливаем сумму 

        # пока остаются элементы, которые мы можем добавить в сумму
        while r > 0:
            total += self.t[r]
            r -= r & -r

        return total

    def range_sum(self, l, r):
        """
        Возвращает сумму на отрезке [l, r]

        l и r — индексы исходного массива,
        индексация начинается с 0
        """

        return self.prefix_sum(r) - self.prefix_sum(l - 1)

    def print_tree(self):
        """
        Выводит внутренний массив дерева Фенвика

        Это вспомогательный метод для проверки
        и визуализации структуры
        """

        print(self.t)

    def get_tree(self):
        """
        Возвращает копию внутреннего массива дерева,
        чтобы внешний код не мог изменить внутреннюю структуру дерева
        """

        return self.t.copy()


a = [2, 1, 4, 3, 5]

t = FenwickTree(a)
t.print_tree()

print(t.prefix_sum(2)) # 7
print(t.range_sum(1, 3)) # 8

t.set(2, 5)
t.print_tree()